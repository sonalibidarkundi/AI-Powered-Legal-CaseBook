-- ----------------------------------------------------------------------------
-- 1. Add DEADLINE column to CASE_ASSIGNMENTS table
-- ----------------------------------------------------------------------------
DECLARE
    v_col_exists NUMBER := 0;
BEGIN
    SELECT COUNT(*) INTO v_col_exists
    FROM user_tab_cols
    WHERE table_name = 'CASE_ASSIGNMENTS' AND column_name = 'DEADLINE';

    IF v_col_exists = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE CASE_ASSIGNMENTS ADD (DEADLINE TIMESTAMP WITH TIME ZONE)';
        DBMS_OUTPUT.PUT_LINE('Added column DEADLINE to CASE_ASSIGNMENTS table.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Column DEADLINE already exists on CASE_ASSIGNMENTS table.');
    END IF;
END;
/

-- ----------------------------------------------------------------------------
-- 2. Create RESEARCH_TASKS table
-- ----------------------------------------------------------------------------
DECLARE
    v_table_exists NUMBER := 0;
BEGIN
    SELECT COUNT(*) INTO v_table_exists
    FROM user_tables
    WHERE table_name = 'RESEARCH_TASKS';

    IF v_table_exists = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE RESEARCH_TASKS (
                TASK_ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                CASE_ID         NUMBER                          NOT NULL,
                STAFF_ID        NUMBER                          NOT NULL,
                ASSIGNED_BY     NUMBER                          NOT NULL,
                TITLE           VARCHAR2(255)                   NOT NULL,
                INSTRUCTIONS    CLOB,
                STATUS          VARCHAR2(30) DEFAULT ''PENDING'' NOT NULL,
                PRIORITY        VARCHAR2(20) DEFAULT ''MEDIUM''  NOT NULL,
                DUE_DATE        TIMESTAMP WITH TIME ZONE,
                RESEARCH_NOTES  CLOB,
                CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

                CONSTRAINT PK_RESEARCH_TASKS PRIMARY KEY (TASK_ID),
                CONSTRAINT FK_RT_CASE FOREIGN KEY (CASE_ID)
                    REFERENCES CASES(CASE_ID) ON DELETE CASCADE,
                CONSTRAINT FK_RT_STAFF FOREIGN KEY (STAFF_ID)
                    REFERENCES STAFF(STAFF_ID) ON DELETE CASCADE,
                CONSTRAINT FK_RT_ASSIGNED_BY FOREIGN KEY (ASSIGNED_BY)
                    REFERENCES USERS(USER_ID),
                CONSTRAINT CHK_RT_STATUS CHECK (STATUS IN (''PENDING'', ''IN_PROGRESS'', ''COMPLETED'')),
                CONSTRAINT CHK_RT_PRIORITY CHECK (PRIORITY IN (''LOW'', ''MEDIUM'', ''HIGH'', ''URGENT''))
            )
        ';
        EXECUTE IMMEDIATE 'COMMENT ON TABLE RESEARCH_TASKS IS ''Legal research tasks and investigative assignments allocated to staff members.''';
        DBMS_OUTPUT.PUT_LINE('Created table RESEARCH_TASKS.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Table RESEARCH_TASKS already exists.');
    END IF;
END;
/

-- ----------------------------------------------------------------------------
-- 3. Create Indexes for High Performance Queries on RESEARCH_TASKS
-- ----------------------------------------------------------------------------
DECLARE
    v_idx_exists NUMBER := 0;
BEGIN
    -- Index on STAFF_ID for rapid filtering of authorized staff tasks
    SELECT COUNT(*) INTO v_idx_exists
    FROM user_indexes
    WHERE index_name = 'IDX_RT_STAFF';

    IF v_idx_exists = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_RT_STAFF ON RESEARCH_TASKS(STAFF_ID)';
        DBMS_OUTPUT.PUT_LINE('Created index IDX_RT_STAFF.');
    END IF;

    -- Index on CASE_ID
    SELECT COUNT(*) INTO v_idx_exists
    FROM user_indexes
    WHERE index_name = 'IDX_RT_CASE';

    IF v_idx_exists = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_RT_CASE ON RESEARCH_TASKS(CASE_ID)';
        DBMS_OUTPUT.PUT_LINE('Created index IDX_RT_CASE.');
    END IF;

    -- Index on STATUS
    SELECT COUNT(*) INTO v_idx_exists
    FROM user_indexes
    WHERE index_name = 'IDX_RT_STATUS';

    IF v_idx_exists = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_RT_STATUS ON RESEARCH_TASKS(STATUS)';
        DBMS_OUTPUT.PUT_LINE('Created index IDX_RT_STATUS.');
    END IF;

    -- Index on DUE_DATE for deadline sorting
    SELECT COUNT(*) INTO v_idx_exists
    FROM user_indexes
    WHERE index_name = 'IDX_RT_DUE_DATE';

    IF v_idx_exists = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_RT_DUE_DATE ON RESEARCH_TASKS(DUE_DATE)';
        DBMS_OUTPUT.PUT_LINE('Created index IDX_RT_DUE_DATE.');
    END IF;
END;
/


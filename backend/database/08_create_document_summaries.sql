-- ============================================================================
-- SCRIPT: 08_create_document_summaries.sql
-- PROJECT: AI-Powered Advocate Legal CaseBook (Stage 6.2 - Grok AI Integration)
-- DESCRIPTION: Oracle-compatible migration script adding DOCUMENT_SUMMARIES table
--              for persisting Grok AI structured summaries, model identifiers,
--              extraction status, and verification timestamps.
-- IDEMPOTENT: Safe to run repeatedly without duplicate table or constraint errors.
-- COMPATIBILITY: Oracle Database 12c, 18c, 19c, 21c, 23ai
-- ============================================================================

DECLARE
    v_table_exists NUMBER := 0;
BEGIN
    SELECT COUNT(*) INTO v_table_exists
    FROM user_tables
    WHERE table_name = 'DOCUMENT_SUMMARIES';

    IF v_table_exists = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE DOCUMENT_SUMMARIES (
                SUMMARY_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                DOCUMENT_ID     NUMBER                          NOT NULL,
                CASE_ID         NUMBER                          NOT NULL,
                GENERATED_BY    NUMBER                          NOT NULL,
                SUMMARY_TEXT    CLOB                            NOT NULL,
                STRUCTURED_JSON CLOB,
                MODEL_NAME      VARCHAR2(100) DEFAULT ''grok-2-latest'' NOT NULL,
                STATUS          VARCHAR2(30) DEFAULT ''SUCCESS'' NOT NULL,
                ERROR_MESSAGE   VARCHAR2(1000),
                CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

                CONSTRAINT PK_DOCUMENT_SUMMARIES PRIMARY KEY (SUMMARY_ID),
                CONSTRAINT FK_DS_DOCUMENT FOREIGN KEY (DOCUMENT_ID)
                    REFERENCES DOCUMENTS(DOCUMENT_ID) ON DELETE CASCADE,
                CONSTRAINT FK_DS_CASE FOREIGN KEY (CASE_ID)
                    REFERENCES CASES(CASE_ID) ON DELETE CASCADE,
                CONSTRAINT FK_DS_GENERATED_BY FOREIGN KEY (GENERATED_BY)
                    REFERENCES USERS(USER_ID),
                CONSTRAINT UQ_DS_DOCUMENT UNIQUE (DOCUMENT_ID),
                CONSTRAINT CHK_DS_STATUS CHECK (STATUS IN (''SUCCESS'', ''FAILED'', ''PROCESSING''))
            )
        ';
        EXECUTE IMMEDIATE 'COMMENT ON TABLE DOCUMENT_SUMMARIES IS ''Grok AI structured legal summaries for uploaded case filings and certified documents.''';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_DS_CASE_ID ON DOCUMENT_SUMMARIES(CASE_ID)';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_DS_DOC_ID ON DOCUMENT_SUMMARIES(DOCUMENT_ID)';
        DBMS_OUTPUT.PUT_LINE('Created table DOCUMENT_SUMMARIES and associated indexes.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Table DOCUMENT_SUMMARIES already exists.');
    END IF;
END;
/

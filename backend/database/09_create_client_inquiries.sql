-- ============================================================================
-- SCRIPT: 09_create_client_inquiries.sql
-- PROJECT: AI-Powered Advocate Legal CaseBook (Stage 7 - Client Dashboard)
-- DESCRIPTION: Oracle-compatible migration script adding CLIENT_INQUIRIES table
--              for client-to-advocate genuine advisory communication, tracking
--              status, subject matter, message text, and audit records.
-- IDEMPOTENT: Safe to run repeatedly without duplicate table or constraint errors.
-- COMPATIBILITY: Oracle Database 12c, 18c, 19c, 21c, 23ai
-- ============================================================================

DECLARE
    v_table_exists NUMBER := 0;
BEGIN
    SELECT COUNT(*) INTO v_table_exists
    FROM user_tables
    WHERE table_name = 'CLIENT_INQUIRIES';

    IF v_table_exists = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE CLIENT_INQUIRIES (
                INQUIRY_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                CASE_ID         NUMBER                          NOT NULL,
                CLIENT_ID       NUMBER                          NOT NULL,
                ADVOCATE_ID     NUMBER                          NOT NULL,
                SUBJECT         VARCHAR2(255)                   NOT NULL,
                MESSAGE_TEXT    CLOB                            NOT NULL,
                STATUS          VARCHAR2(30) DEFAULT ''SUBMITTED'' NOT NULL,
                CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

                CONSTRAINT PK_CLIENT_INQUIRIES PRIMARY KEY (INQUIRY_ID),
                CONSTRAINT FK_CI_CASE FOREIGN KEY (CASE_ID)
                    REFERENCES CASES(CASE_ID) ON DELETE CASCADE,
                CONSTRAINT FK_CI_CLIENT FOREIGN KEY (CLIENT_ID)
                    REFERENCES CLIENTS(CLIENT_ID) ON DELETE CASCADE,
                CONSTRAINT FK_CI_ADVOCATE FOREIGN KEY (ADVOCATE_ID)
                    REFERENCES USERS(USER_ID),
                CONSTRAINT CHK_CI_STATUS CHECK (STATUS IN (''SUBMITTED'', ''ACKNOWLEDGED'', ''IN_REVIEW'', ''RESOLVED''))
            )
        ';
        EXECUTE IMMEDIATE 'COMMENT ON TABLE CLIENT_INQUIRIES IS ''Authorized client communications and advisory inquiries directed to assigned counsel.''';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_CI_CASE_ID ON CLIENT_INQUIRIES(CASE_ID)';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_CI_CLIENT_ID ON CLIENT_INQUIRIES(CLIENT_ID)';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_CI_ADVOCATE_ID ON CLIENT_INQUIRIES(ADVOCATE_ID)';
        DBMS_OUTPUT.PUT_LINE('Created table CLIENT_INQUIRIES and associated indexes.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Table CLIENT_INQUIRIES already exists.');
    END IF;
END;
/

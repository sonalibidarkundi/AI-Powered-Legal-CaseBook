-- DESCRIPTION: Creates the complete relational schema in Oracle Database.
-- COMPATIBILITY: Oracle Database 12c, 18c, 19c, 21c, 23ai
-- NOTES: Uses IDENTITY columns for primary keys, strict foreign key constraints,
--        and CHECK constraints for domain integrity.

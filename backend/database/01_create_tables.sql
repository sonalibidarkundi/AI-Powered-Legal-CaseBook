-- Optional Cleanup Section: Safely drop existing tables if rerunning script
BEGIN
    FOR t IN (
        SELECT table_name FROM user_tables 
        WHERE table_name IN (
            'AUDIT_LOGS', 'HEARINGS', 'DOCUMENTS', 'CASE_ASSIGNMENTS',
            'CASE_CLIENTS', 'CASES', 'STAFF', 'CLIENTS', 'USERS'
        )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 1. TABLE: USERS
-- Master identity store for all system actors (Advocates, Staff, Clients).
-- Passwords must ALWAYS be stored as secure salted hashes, NEVER plaintext.
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    USER_ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    FULL_NAME       VARCHAR2(150)                   NOT NULL,
    EMAIL           VARCHAR2(255)                   NOT NULL,
    PASSWORD_HASH   VARCHAR2(255)                   NOT NULL,
    ROLE            VARCHAR2(20)                    NOT NULL,
    ACCOUNT_STATUS  VARCHAR2(20) DEFAULT 'PENDING'  NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CHK_USERS_ROLE CHECK (ROLE IN ('ADVOCATE', 'STAFF', 'CLIENT')),
    CONSTRAINT CHK_USERS_STATUS CHECK (ACCOUNT_STATUS IN ('PENDING', 'ACTIVE', 'SUSPENDED', 'REJECTED'))
);

COMMENT ON TABLE USERS IS 'Primary user table holding authentication credentials and high-level roles.';
COMMENT ON COLUMN USERS.PASSWORD_HASH IS 'Cryptographic hash generated by backend (e.g., scrypt or pbkdf2), never plaintext.';
COMMENT ON COLUMN USERS.ROLE IS 'Primary system role: ADVOCATE (Admin), STAFF, or CLIENT.';

-- ----------------------------------------------------------------------------
-- 2. TABLE: CLIENTS
-- Profile details specific to legal clients and case litigants.
-- ----------------------------------------------------------------------------
CREATE TABLE CLIENTS (
    CLIENT_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USER_ID         NUMBER                          NOT NULL,
    PHONE           VARCHAR2(30),
    ADDRESS         VARCHAR2(400),
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    
    CONSTRAINT PK_CLIENTS PRIMARY KEY (CLIENT_ID),
    CONSTRAINT UQ_CLIENTS_USER UNIQUE (USER_ID),
    CONSTRAINT FK_CLIENTS_USER FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

COMMENT ON TABLE CLIENTS IS 'Client demographic data linked 1-to-1 to a user account.';

-- ----------------------------------------------------------------------------
-- 3. TABLE: STAFF
-- Profile details for paralegals, law clerks, and administrative assistants.
-- ----------------------------------------------------------------------------
CREATE TABLE STAFF (
    STAFF_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USER_ID         NUMBER                          NOT NULL,
    EMPLOYEE_CODE   VARCHAR2(50)                    NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    
    CONSTRAINT PK_STAFF PRIMARY KEY (STAFF_ID),
    CONSTRAINT UQ_STAFF_USER UNIQUE (USER_ID),
    CONSTRAINT UQ_STAFF_EMP_CODE UNIQUE (EMPLOYEE_CODE),
    CONSTRAINT FK_STAFF_USER FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

COMMENT ON TABLE STAFF IS 'Staff members and legal clerks employed by or assigned to law offices.';

-- ----------------------------------------------------------------------------
-- 4. TABLE: CASES
-- Legal cases, proceedings, lawsuits, and matters managed by Advocates.
-- ----------------------------------------------------------------------------
CREATE TABLE CASES (
    CASE_ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CASE_NUMBER     VARCHAR2(50)                    NOT NULL,
    TITLE           VARCHAR2(255)                   NOT NULL,
    DESCRIPTION     CLOB,
    CASE_STATUS     VARCHAR2(30) DEFAULT 'OPEN'     NOT NULL,
    CASE_TYPE       VARCHAR2(50) DEFAULT 'CIVIL'    NOT NULL,
    CREATED_BY      NUMBER                          NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    
    CONSTRAINT PK_CASES PRIMARY KEY (CASE_ID),
    CONSTRAINT UQ_CASES_NUMBER UNIQUE (CASE_NUMBER),
    CONSTRAINT FK_CASES_CREATED_BY FOREIGN KEY (CREATED_BY)
        REFERENCES USERS(USER_ID),
    CONSTRAINT CHK_CASES_STATUS CHECK (
        CASE_STATUS IN ('OPEN', 'PENDING_HEARING', 'IN_TRIAL', 'DISPOSED', 'CLOSED', 'ARCHIVED')
    ),
    CONSTRAINT CHK_CASES_TYPE CHECK (
        CASE_TYPE IN ('CIVIL', 'CRIMINAL', 'CORPORATE', 'CONSTITUTIONAL', 'FAMILY', 'TAXATION', 'ARBITRATION', 'LABOR', 'OTHER')
    )
);

COMMENT ON TABLE CASES IS 'Primary case registry recording title, filing number, and status.';

-- ----------------------------------------------------------------------------
-- 5. TABLE: CASE_CLIENTS
-- Associative entity mapping many-to-many relationship between Cases and Clients.
-- ----------------------------------------------------------------------------
CREATE TABLE CASE_CLIENTS (
    CASE_ID         NUMBER                          NOT NULL,
    CLIENT_ID       NUMBER                          NOT NULL,
    
    CONSTRAINT PK_CASE_CLIENTS PRIMARY KEY (CASE_ID, CLIENT_ID),
    CONSTRAINT FK_CC_CASE FOREIGN KEY (CASE_ID)
        REFERENCES CASES(CASE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_CC_CLIENT FOREIGN KEY (CLIENT_ID)
        REFERENCES CLIENTS(CLIENT_ID) ON DELETE CASCADE
);

COMMENT ON TABLE CASE_CLIENTS IS 'Associative table connecting cases to one or more clients.';

-- ----------------------------------------------------------------------------
-- 6. TABLE: CASE_ASSIGNMENTS
-- Tracks assignment of law firm staff (paralegals, clerks) to specific cases.
-- ----------------------------------------------------------------------------
CREATE TABLE CASE_ASSIGNMENTS (
    ASSIGNMENT_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CASE_ID             NUMBER                      NOT NULL,
    STAFF_ID            NUMBER                      NOT NULL,
    ASSIGNED_BY         NUMBER                      NOT NULL,
    ASSIGNED_AT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ASSIGNMENT_STATUS   VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL,
    INSTRUCTIONS        VARCHAR2(1000),
    
    CONSTRAINT PK_CASE_ASSIGNMENTS PRIMARY KEY (ASSIGNMENT_ID),
    CONSTRAINT FK_CA_CASE FOREIGN KEY (CASE_ID)
        REFERENCES CASES(CASE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_CA_STAFF FOREIGN KEY (STAFF_ID)
        REFERENCES STAFF(STAFF_ID) ON DELETE CASCADE,
    CONSTRAINT FK_CA_ASSIGNED_BY FOREIGN KEY (ASSIGNED_BY)
        REFERENCES USERS(USER_ID),
    CONSTRAINT CHK_CA_STATUS CHECK (ASSIGNMENT_STATUS IN ('ACTIVE', 'COMPLETED', 'REVOKED'))
);

COMMENT ON TABLE CASE_ASSIGNMENTS IS 'Staff task allocations on active case files.';

-- ----------------------------------------------------------------------------
-- 7. TABLE: DOCUMENTS
-- Case filings, evidence, petitions, and legal briefs.
-- ----------------------------------------------------------------------------
CREATE TABLE DOCUMENTS (
    DOCUMENT_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CASE_ID         NUMBER                          NOT NULL,
    UPLOADED_BY     NUMBER                          NOT NULL,
    FILE_NAME       VARCHAR2(255)                   NOT NULL,
    MIME_TYPE       VARCHAR2(100)                   NOT NULL,
    STORAGE_KEY     VARCHAR2(500)                   NOT NULL,
    UPLOADED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    
    CONSTRAINT PK_DOCUMENTS PRIMARY KEY (DOCUMENT_ID),
    CONSTRAINT FK_DOCS_CASE FOREIGN KEY (CASE_ID)
        REFERENCES CASES(CASE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_DOCS_UPLOADED_BY FOREIGN KEY (UPLOADED_BY)
        REFERENCES USERS(USER_ID)
);

COMMENT ON TABLE DOCUMENTS IS 'Metadata and secure storage pointers for documents linked to a case.';

-- ----------------------------------------------------------------------------
-- 8. TABLE: HEARINGS
-- Court dates, trial proceedings, motion schedules, and judicial sessions.
-- ----------------------------------------------------------------------------
CREATE TABLE HEARINGS (
    HEARING_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CASE_ID         NUMBER                          NOT NULL,
    HEARING_DATE    TIMESTAMP WITH TIME ZONE        NOT NULL,
    COURT_NAME      VARCHAR2(200)                   NOT NULL,
    NOTES           CLOB,
    HEARING_STATUS  VARCHAR2(30) DEFAULT 'SCHEDULED' NOT NULL,
    
    CONSTRAINT PK_HEARINGS PRIMARY KEY (HEARING_ID),
    CONSTRAINT FK_HEARINGS_CASE FOREIGN KEY (CASE_ID)
        REFERENCES CASES(CASE_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_HEARINGS_STATUS CHECK (
        HEARING_STATUS IN ('SCHEDULED', 'ADJOURNED', 'CONCLUDED', 'CANCELLED')
    )
);

COMMENT ON TABLE HEARINGS IS 'Calendar of court dates and hearing proceedings.';

-- ----------------------------------------------------------------------------
-- 9. TABLE: AUDIT_LOGS
-- Comprehensive immutable audit trail for security, compliance, and forensics.
-- ----------------------------------------------------------------------------
CREATE TABLE AUDIT_LOGS (
    AUDIT_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ACTOR_USER_ID   NUMBER,
    ACTION_TYPE     VARCHAR2(50)                    NOT NULL,
    ENTITY_TYPE     VARCHAR2(50)                    NOT NULL,
    ENTITY_ID       NUMBER,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    
    CONSTRAINT PK_AUDIT_LOGS PRIMARY KEY (AUDIT_ID),
    CONSTRAINT FK_AUDIT_ACTOR FOREIGN KEY (ACTOR_USER_ID)
        REFERENCES USERS(USER_ID) ON DELETE SET NULL
);

COMMENT ON TABLE AUDIT_LOGS IS 'System audit trail tracking security events, registrations, and modifications.';

-- Commit schema creation
COMMIT;
